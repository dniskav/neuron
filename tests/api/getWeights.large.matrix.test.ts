describe('getWeights con arrays grandes (sin RangeError)', () => {
  // Hand count: WeightMatrix(1, 200000) → 1 · 200000 = 200000 pesos.
  it('WeightMatrix(1, 200000): longitud 200000 y set(get()) es identidad', () => {
    const m = new WeightMatrix(1, 200000)
    const before = m.getWeights()
    expect(before.length).toBe(200000)
    m.setWeights(before)
    expect(m.getWeights()).toEqual(before)
  })

  // Hand count: EmbeddingMatrix(1, 200000) → 1 · 200000 = 200000 pesos.
  it('EmbeddingMatrix(1, 200000): longitud 200000 y set(get()) es identidad', () => {
    const m = new EmbeddingMatrix(1, 200000)
    const before = m.getWeights()
    expect(before.length).toBe(200000)
    m.setWeights(before)
    expect(m.getWeights()).toEqual(before)
  })

  // Hand count: Wq (1 × 200000) + Wk (1 × 200000) + Wv (1 × 200000) = 600000 pesos.
  it('AttentionHead(200000, 1, 1): longitud 3 · 200000 = 600000 y set(get()) es identidad', () => {
    const head = new AttentionHead(200000, 1, 1)
    const before = head.getWeights()
    expect(before.length).toBe(600000)
    head.setWeights(before)
    expect(head.getWeights()).toEqual(before)
  })

  // Hand count (d_model 1, 1 cabeza, d_ff 200000):
  //   attn = 3 (Wq, Wk, Wv de 1×1) + 1 (Wo de 1×1) = 4
  //   norm1 = 2 (gamma, beta); ff1 = 200000 · 1; b1 = 200000
  //   ff2 = 1 · 200000; b2 = 1; norm2 = 2
  //   total = 4 + 2 + 200000 + 200000 + 200000 + 1 + 2 = 600009
  it('TransformerBlock(d_model 1, 1 cabeza, d_ff 200000): longitud 600009 y set(get()) es identidad', () => {
    const block = new TransformerBlock({ d_model: 1, nHeads: 1, d_ff: 200000 })
    const before = block.getWeights()
    expect(before.length).toBe(600009)
    block.setWeights(before)
    expect(block.getWeights()).toEqual(before)
  })
})
